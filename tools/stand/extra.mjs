import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(process.env.NODE_TOOLS || '/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const srv = spawn('node', [path.join(HERE, 'server.mjs')], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 600));
const fails = []; const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fails.push(m); };
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto('http://localhost:8765/');
await page.waitForFunction(() => window.Wardrobe?.version);
await page.evaluate(() => Wardrobe.open('closet'));
await sleep(500);
await page.locator('[data-act="new-item"]').first().click(); await sleep(300);
await page.locator('[data-act="to-look-add"]').click(); await sleep(400);
ok(await page.locator('#wd-panel.wd-full').count() === 1 && await page.locator('.wd-lk-drop').count() === 1, 'из шкафа: «Целый образ?» → страница образов + «Новый образ»');
await page.locator('[data-act="look-from-worn"]').click(); await sleep(400);
ok(await page.locator('[data-input="setcat"]').count() === 1, '«Что надето сейчас» → состав образа с выбором раздела');
await page.locator('[data-input="setname"]').fill('Хеди — халат и кольцо');
await page.locator('[data-input="setcat"]').selectOption('__new'); await sleep(200);
await page.locator('[data-input="catnew"]').fill('Лаба');
await page.locator('[data-act="set-save"]').click(); await sleep(400);
const s = await page.evaluate(() => SillyTavern.getContext().extensionSettings.wardrobe);
const set = s.sets.find(x => x.name === 'Хеди — халат и кольцо');
ok(set && set.cat === 'Лаба' && s.cats.includes('Лаба'), `свой раздел «Лаба» создан и назначен (${set?.cat})`);
ok(set && !set.itemIds.includes('i12') && set.itemIds.includes('i4'), 'закреплённое кольцо в образ не попало, халат — да');
ok(await page.locator('.wd-modal-title').innerText().then(t => t.includes('халат и кольцо')), 'после сохранения открылась карточка нового образа');
await page.locator('.wd-modal .wd-x').click(); await sleep(250);
ok((await page.locator('.wd-lk-cats .wd-chip').allInnerTexts()).some(t => t.includes('Лаба')), 'чип «Лаба» появился');
await page.locator('.wd-lk-cats .wd-chip:has-text("Лаба")').click(); await sleep(300);
await page.locator('.wd-lk-card .wd-lk-info').first().click(); await sleep(300);
await page.locator('.wd-modal [data-act="look-wear-all"]').click(); await sleep(400);
const worn = await page.evaluate(() => SillyTavern.getContext().chatMetadata.wardrobe.chars['Хеди'].worn.map(e => e.name));
ok(worn.includes('белый лабораторный халат') && worn.includes('обручальное кольцо'), `«Переодеть полностью»: ${worn.join(', ')}`);
await page.evaluate(() => { document.querySelector('[data-act="look-back"]').click(); });
await sleep(300);
await page.evaluate(() => Wardrobe.openLooks('Bucky Barnes', 'Миссия')); await sleep(400);
ok(await page.locator('.wd-lk-who.on[data-name="Bucky Barnes"]').count() === 1 && await page.locator('.wd-lk-cats .wd-chip.on').innerText().then(t => t.includes('Миссия')), 'openLooks(Баки, Миссия)');
ok(JSON.stringify(await page.evaluate(() => Wardrobe.cats())).includes('Лаба'), 'Wardrobe.cats() отдаёт разделы');
await page.screenshot({ path: path.join(HERE, 'shots/30-bucky-mission.png') });
console.log('ошибки:', errs.length ? errs : 'нет');
await b.close(); srv.kill();
process.exit(fails.length ? 1 : 0);
