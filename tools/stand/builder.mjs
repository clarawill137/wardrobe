// Состав образа (1.8.3): у образа владельца — только его вещи, разделы чипами и подзаголовками, у общего — люди;
// стиль: вещи шкафа — прежний карандаш, образы — масло.
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(process.env.NODE_TOOLS || '/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const srv = spawn('node', [path.join(HERE, 'server.mjs')], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 600));
const fails = [];
const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fails.push(m); };
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
const errs = [];
page.on('pageerror', e => errs.push(e.message));
await page.goto('http://localhost:8765/');
await page.waitForFunction(() => window.Wardrobe?.version);
const S = () => page.evaluate(() => SillyTavern.getContext().extensionSettings.wardrobe);
const ids = () => page.$$eval('.wd-modal [data-sb-grid] .wd-card', els => els.map(e => e.dataset.id));
const secs = () => page.$$eval('.wd-modal .wd-sb-sec', els => els.map(e => e.textContent.replace(/\s+\d+$/, '').trim()));

console.log('— стиль');
let s = await S();
ok(s.imgStyle === 'oil' && s.itemStyle === 'clover', `образы — ${s.imgStyle}, вещи — ${s.itemStyle} (прежний стиль)`);

ok(s.cats.join('|').includes('Спортивное|Тёплое'), `раздел «Тёплое» добавлен после «Спортивного»: ${s.cats.join(', ')}`);

console.log('— состав образа Хеди');
await page.evaluate(() => Wardrobe.open('looks', 'Хеди'));
await page.waitForFunction(() => SillyTavern.getContext().extensionSettings.wardrobe.migrSlice === true, null, { timeout: 5000 });
await sleep(300);
ok(await page.locator('#wd-panel').getByText('Тёплое').count() > 0, 'на странице образов есть раздел 🧣 «Тёплое» (даже пустой)');
await page.evaluate(() => { document.querySelector('.wd-lk-card [data-act="look-open"][data-id="s1"], .wd-lk-card[data-id="s1"] [data-act="look-open"]')?.click(); });
await sleep(300);
if (!(await page.locator('.wd-modal [data-act="set-edit"]').count())) await page.evaluate(() => { const el = [...document.querySelectorAll('[data-act="look-open"]')].find(x => x.dataset.id === 's1'); el?.click(); });
await sleep(300);
await page.locator('.wd-modal [data-act="set-edit"]').first().click();
await sleep(300);
let got = await ids();
ok(got.length && got.every(id => ['i1', 'i2', 'i3', 'i4', 'i5', 'i6', 'i7', 'i8', 'i12'].includes(id)), `только вещи Хеди: ${got.join(',')}`);
ok(!got.includes('i9') && !got.includes('i11') && !got.includes('i13'), 'ни вещей Баки, ни общих');
const sec = await secs();
ok(sec.includes('👗 Платье / комбинезон') && sec.includes('👢 Обувь') && sec.includes('💍 Аксессуары'), `разделы подзаголовками: ${sec.join(' | ')}`);
ok(await page.locator('.wd-modal [data-act="sb-person"]').count() === 0, 'у образа Хеди чипов людей нет');
await page.locator('.wd-modal [data-act="sb-slot"][data-slot="shoes"]').click(); await sleep(200);
got = await ids();
ok(got.join(',') === 'i2,i8', `чип «Обувь» — только обувь: ${got.join(',')}`);
await page.locator('.wd-modal .wd-card[data-id="i8"]').click();
await page.locator('.wd-modal [data-act="sb-slot"][data-slot="all"]').click(); await sleep(200);
ok(await page.locator('.wd-modal .wd-card.on[data-id="i8"]').count() === 1, 'выбор не теряется при смене раздела');
await page.locator('.wd-modal [data-act="sb-slot"][data-slot="acc"]').click(); await sleep(200);
await page.locator('.wd-modal [data-act="set-save"]').click(); await sleep(400);
s = await S();
ok(s.sets.find(x => x.id === 's1').itemIds.join(',') === 'i1,i2,i3,i8', `сохранились и вещи скрытых разделов: ${s.sets.find(x => x.id === 's1').itemIds}`);

console.log('— общий образ');
await page.evaluate(() => { document.querySelector('.wd-modal-host').classList.remove('on'); });
await page.locator('.wd-lk-add').click(); await sleep(300);
await page.locator('[data-act="set-new"]').click(); await sleep(300);
await page.locator('[data-input="setowner"]').selectOption(''); await sleep(250);
ok(await page.locator('.wd-modal [data-act="sb-person"]').count() >= 3, 'у общего образа — чипы людей (все, общее, Хеди, Баки…)');
got = await ids();
ok(got.includes('i9') && got.includes('i1') && got.includes('i11'), '«все» — вещи всех');
await page.locator('.wd-modal [data-act="sb-person"][data-owner="Bucky Barnes"]').click(); await sleep(200);
got = await ids();
ok(got.length && got.every(id => ['i9', 'i10'].includes(id)), `чип «Баки» — только его: ${got.join(',')}`);
await page.locator('[data-input="setowner"]').selectOption('Хеди'); await sleep(250);
got = await ids();
ok(got.length && got.every(id => ['i1', 'i2', 'i3', 'i4', 'i5', 'i6', 'i7', 'i8', 'i12'].includes(id)), 'сменила «Чей» на Хеди — сетка только её');

console.log('— картинки: вещь карандашом, образ маслом');
await page.evaluate(() => { document.querySelector('.wd-modal-host').classList.remove('on'); window.__gens.length = 0; });
await page.evaluate(() => Wardrobe.open('closet', 'Хеди')); await sleep(300);
await page.evaluate(() => { const el = [...document.querySelectorAll('[data-act="item-menu"]')].find(x => x.dataset.id === 'i3'); el?.click(); });
await sleep(300);
const btn = await page.locator('.wd-modal [data-act="item-draw"]').innerText();
ok(/Карандаш/.test(btn), `кнопка вещи — «${btn.trim()}»`);
await page.locator('.wd-modal [data-act="item-draw"]').click();
await page.waitForFunction(() => window.__gens.length >= 1, null, { timeout: 15000 });
let g = await page.evaluate(() => window.__gens[0]);
let txt = g.messages[0].content.find(p => p.type === 'text').text;
ok(/colored-pencil/.test(txt) && g.image_config.aspect_ratio === '4:3', `вещь: карандаш, 4:3 (${g.image_config.aspect_ratio})`);
await page.evaluate(() => { window.__gens.length = 0; Wardrobe.drawSet('s2'); });
await page.waitForFunction(() => window.__gens.length >= 1, null, { timeout: 15000 });
g = await page.evaluate(() => window.__gens[0]);
txt = g.messages[0].content.find(p => p.type === 'text').text;
ok(!/colored-pencil/.test(txt) && g.image_config.aspect_ratio === '2:3', `образ: масло, 2:3 (${g.image_config.aspect_ratio})`);

console.log('— окно стиля: два ряда');
await sleep(500);
await page.evaluate(() => { const h = document.querySelector('.wd-modal-host'); if (h) { h.classList.remove('on'); h.innerHTML = ''; } });
await page.evaluate(() => Wardrobe.open('looks', 'Хеди')); await sleep(300);
await page.locator('[data-act="look-style"]').click(); await sleep(300);
ok(await page.locator('.wd-modal [data-act="style-pick"][data-for="items"]').count() > 3 && await page.locator('.wd-modal [data-act="style-pick"][data-for="looks"]').count() > 3, 'есть ряд «Образы» и ряд «Вещи в шкафу»');
await page.locator('.wd-modal [data-act="style-pick"][data-for="items"][data-v="sketch"]').click(); await sleep(300);
s = await S();
ok(s.itemStyle === 'sketch' && s.imgStyle === 'oil', 'выбор в ряду вещей меняет только вещи');

console.log('ошибки:', errs.length ? errs : 'нет');
await b.close(); srv.kill();
console.log(fails.length ? `\nПРОВАЛЕНО: ${fails.length}` : '\nвсё прошло');
process.exit(fails.length ? 1 : 0);
